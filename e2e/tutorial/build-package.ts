/**
 * Writes the generated half of the video production package in docs/video-tutorial from
 * scenes.ts: the production script, the voiceover script, the storyboard, the subtitles (SRT) and
 * the chapter timestamps with the publishing details. `pnpm tutorial:package`.
 *
 * Timings are planned from the narration (150 words a minute, see scenes.ts) plus a chapter card
 * between chapters. Once the voiceover is recorded, re-time the SRT to it in the editor.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { CHAPTER_CARD_SECONDS, CHAPTERS, narrationSeconds, sceneSeconds, slug, VIDEO, type Chapter, type Scene } from './scenes';

const OUT = path.resolve(import.meta.dirname, '../../docs/video-tutorial');
const GENERATED = '<!-- Generated by e2e/tutorial/build-package.ts from e2e/tutorial/scenes.ts. Edit the scenes, then run `pnpm tutorial:package`. -->';

/** 75 → "1:15"; with hours when the video is that long. */
function clock(total: number): string {
  const s = Math.round(total);
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const sec = String(s % 60).padStart(2, '0');
  return h ? `${h}:${String(m).padStart(2, '0')}:${sec}` : `${m}:${sec}`;
}

/** SRT time: 00:01:02,500 */
function srtTime(total: number): string {
  const ms = Math.round(total * 1000);
  const h = Math.floor(ms / 3600_000);
  const m = Math.floor((ms % 3600_000) / 60_000);
  const s = Math.floor((ms % 60_000) / 1000);
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')},${String(ms % 1000).padStart(3, '0')}`;
}

const clipName = (s: Scene) => (s.app === 'edit' ? '— (made in the editor)' : `\`${s.id}-${slug(s.title)}.webm\``);
const words = (text: string) => text.trim().split(/\s+/).filter(Boolean).length;

interface Timed {
  chapter: Chapter;
  scene: Scene;
  start: number;
  end: number;
}

/** Every scene on the planned timeline, with a chapter card before each chapter after the first. */
function timeline(): { scenes: Timed[]; chapters: Array<{ chapter: Chapter; start: number }>; total: number } {
  const scenes: Timed[] = [];
  const chapters: Array<{ chapter: Chapter; start: number }> = [];
  let t = 0;
  for (const [i, chapter] of CHAPTERS.entries()) {
    chapters.push({ chapter, start: t });
    if (i > 0) t += CHAPTER_CARD_SECONDS;
    for (const scene of chapter.scenes) {
      scenes.push({ chapter, scene, start: t, end: t + sceneSeconds(scene) });
      t += sceneSeconds(scene);
    }
  }
  return { scenes, chapters, total: t };
}

/** Splits narration into subtitle cues of at most two lines of 42 characters. */
function cues(text: string): string[] {
  const sentences = text.match(/[^.!?]+[.!?]+|[^.!?]+$/g)?.map((s) => s.trim()) ?? [];
  const out: string[] = [];
  for (const sentence of sentences) {
    let line = '';
    let cue: string[] = [];
    for (const w of sentence.split(/\s+/)) {
      if ((line + ' ' + w).trim().length > 42) {
        cue.push(line);
        line = w;
        if (cue.length === 2) {
          out.push(cue.join('\n'));
          cue = [];
        }
      } else line = (line + ' ' + w).trim();
    }
    if (line) cue.push(line);
    if (cue.length) out.push(cue.join('\n'));
  }
  return out;
}

function productionScript(t: ReturnType<typeof timeline>): string {
  const lines = [
    GENERATED,
    '',
    '# Production script',
    '',
    `**${VIDEO.title}** · ${VIDEO.resolution} · ${VIDEO.language} · planned length **${clock(t.total)}** (${CHAPTERS.length} chapters, ${t.scenes.length} scenes)`,
    '',
    'For every scene: what is on screen, what the presenter does, the narration word for word, the text overlays, the zooms and highlights, and the transition. Each recorded scene has a clip of the real application in `e2e/tutorial/clips` (see the [recording checklist](07-recording-checklist.md)), and a `.markers.json` next to it with the exact second and screen area of every zoom.',
    '',
  ];
  for (const c of CHAPTERS) {
    lines.push(`## Chapter ${c.n} — ${c.title}`, '', `*After this chapter, viewers can:* ${c.goal}`, '');
    for (const s of c.scenes) {
      const at = t.scenes.find((x) => x.scene === s)!;
      lines.push(
        `### Scene ${s.id} — ${s.title}`,
        '',
        '| | |',
        '|---|---|',
        `| **Duration** | ${sceneSeconds(s)} s (narration ${narrationSeconds(s)} s) · starts at ${clock(at.start)} |`,
        `| **Recorded as** | ${s.app === 'edit' ? 'Made in the editor' : `${s.persona === 'guest' ? 'Signed out' : s.persona === 'worker' ? 'Ava Okafor (worker)' : s.persona === 'manager' ? 'Maya Chen (team manager)' : 'Avery Admin (system admin)'} · ${s.app === 'desktop' ? 'desktop app' : 'web app'}`} |`,
        `| **Clip** | ${clipName(s)} |`,
        `| **On screen** | ${s.screen} |`,
        '',
        '**Presenter actions (clicks, typing, navigation)**',
        '',
        ...s.actions.map((a, i) => `${i + 1}. ${a}`),
        '',
        '**Voiceover**',
        '',
        `> ${s.narration}`,
        '',
        `**Text overlays:** ${s.overlays.length ? s.overlays.join(' · ') : 'none'}`,
        '',
        `**Zoom and highlight:** ${s.focus.length ? s.focus.join(' · ') : 'none'}`,
        '',
        `**Transition:** ${s.transition}`,
        '',
      );
    }
  }
  return lines.join('\n');
}

function voiceover(t: ReturnType<typeof timeline>): string {
  const total = t.scenes.reduce((n, s) => n + words(s.scene.narration), 0);
  const lines = [
    GENERATED,
    '',
    '# Voiceover script',
    '',
    `The complete narration, ${total.toLocaleString('en-US')} words, about ${Math.round(total / 150)} minutes at 150 words a minute. Read it in a professional, friendly tone, a little slower than conversation. Leave a breath of about two seconds between scenes, and three seconds at each chapter card.`,
    '',
    'Recording tips: one take per scene, named after the scene number (for example `03.2.wav`), so each take lines up with its clip.',
    '',
  ];
  for (const c of CHAPTERS) {
    lines.push(`## Chapter ${c.n} — ${c.title}`, '');
    for (const s of c.scenes) lines.push(`**[${s.id}] ${s.title}** *(${narrationSeconds(s)} s)*`, '', s.narration, '');
  }
  return lines.join('\n');
}

function storyboard(t: ReturnType<typeof timeline>): string {
  const lines = [
    GENERATED,
    '',
    '# Storyboard',
    '',
    'One row per scene, in order. "Visual" is what the frame shows; "Audio" is the first line of the narration; the clip column names the recording of the real app to use.',
    '',
  ];
  for (const c of CHAPTERS) {
    lines.push(`## Chapter ${c.n} — ${c.title}`, '', '| Scene | Time | Visual | Audio (opens with) | Overlay | Zoom / highlight | Transition | Clip |', '|---|---|---|---|---|---|---|---|');
    for (const s of c.scenes) {
      const at = t.scenes.find((x) => x.scene === s)!;
      const first = s.narration.match(/^[^.!?]+[.!?]/)?.[0] ?? s.narration;
      const cell = (x: string) => x.replace(/\|/g, '\\|');
      lines.push(`| ${s.id} ${cell(s.title)} | ${clock(at.start)}–${clock(at.end)} | ${cell(s.screen)} | “${cell(first)}” | ${cell(s.overlays.join(' · ') || '—')} | ${cell(s.focus.join(' · ') || '—')} | ${cell(s.transition)} | ${clipName(s)} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

function subtitles(t: ReturnType<typeof timeline>): string {
  const out: string[] = [];
  let n = 1;
  for (const x of t.scenes) {
    const parts = cues(x.scene.narration);
    const total = words(x.scene.narration);
    let at = x.start;
    for (const p of parts) {
      const len = (words(p) / total) * narrationSeconds(x.scene);
      out.push(String(n++), `${srtTime(at)} --> ${srtTime(at + len - 0.05)}`, p, '');
      at += len;
    }
  }
  return out.join('\n');
}

function publishing(t: ReturnType<typeof timeline>): string {
  const opening = CHAPTERS[0]!.scenes[0]!;
  const closing = CHAPTERS.at(-1)!.scenes.at(-1)!;
  const chapterList = t.chapters.map(({ chapter, start }) => `${clock(start)} ${chapter.title}`);
  return [
    GENERATED,
    '',
    '# Title, description, chapters and thumbnail',
    '',
    '## Video title',
    '',
    `**${VIDEO.title}**`,
    '',
    'Alternatives:',
    '',
    ...VIDEO.alternativeTitles.map((x) => `- ${x}`),
    '',
    '## Description',
    '',
    'Paste as is. The chapter list makes the video player show chapters (the first must start at 0:00).',
    '',
    '```text',
    ...VIDEO.description.flatMap((p) => [p, '']),
    'Chapters',
    ...chapterList,
    '',
    `Tags: ${VIDEO.tags.join(', ')}`,
    '```',
    '',
    '## Chapter timestamps',
    '',
    `Planned from the narration length; update them after the final edit. Total: **${clock(t.total)}**.`,
    '',
    '| Start | Chapter | Scenes |',
    '|---|---|---|',
    ...t.chapters.map(({ chapter, start }) => `| ${clock(start)} | ${chapter.n}. ${chapter.title} | ${chapter.scenes.map((s) => s.id).join(', ')} |`),
    '',
    '## Opening script',
    '',
    `Scene ${opening.id}, ${narrationSeconds(opening)} s. ${opening.overlays.join(' · ')}.`,
    '',
    `> ${opening.narration}`,
    '',
    '## Closing script',
    '',
    `Scene ${closing.id}, ${narrationSeconds(closing)} s. ${closing.overlays.join(' · ')}.`,
    '',
    `> ${closing.narration}`,
    '',
    '## Thumbnail concept',
    '',
    `- **Image:** ${VIDEO.thumbnail.concept}`,
    `- **Text:** ${VIDEO.thumbnail.text}`,
    `- **Style:** ${VIDEO.thumbnail.style}`,
    '',
  ].join('\n');
}

const t = timeline();
mkdirSync(OUT, { recursive: true });
const files: Record<string, string> = {
  '02-production-script.md': productionScript(t),
  '03-voiceover-script.md': voiceover(t),
  '04-storyboard.md': storyboard(t),
  '05-subtitles.srt': subtitles(t),
  '06-title-description-chapters.md': publishing(t),
};
for (const [name, body] of Object.entries(files)) writeFileSync(path.join(OUT, name), body.endsWith('\n') ? body : `${body}\n`);
console.log(`[tutorial] wrote ${Object.keys(files).length} files to docs/video-tutorial · ${CHAPTERS.length} chapters · ${t.scenes.length} scenes · planned length ${clock(t.total)}`);
